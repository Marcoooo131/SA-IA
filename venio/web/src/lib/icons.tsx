export function iconKey(value: string | null | undefined): string | null {
  if (!value) return null;
  if (ICONS[value]) return value;
  return LEGACY_EMOJI[value] ?? LEGACY_EMOJI[value.replace(/\uFE0F/g, "")] ?? null;
}

/** Icône d'une option de parcours ; rien si la valeur est inconnue (pas d'emoji affiché). */
export function FlowIcon({ name, className = "h-6 w-6" }: { name: string | null | undefined; className?: string }) {
  const key = iconKey(name);
  if (!key) return null;
  const { Icon } = ICONS[key];
  return <Icon aria-hidden className={className} strokeWidth={1.5} />;
}
